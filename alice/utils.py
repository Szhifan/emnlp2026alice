"""Small shared helpers: seeding, device selection, prediction I/O."""

from __future__ import annotations

import csv
import random
from pathlib import Path
from typing import Any, Sequence

import numpy as np
import torch

__all__ = ["set_seed", "default_device", "save_predictions"]


def set_seed(seed: int = 42) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def default_device() -> torch.device:
    if torch.cuda.is_available():
        return torch.device("cuda")
    if torch.backends.mps.is_available():
        return torch.device("mps")
    return torch.device("cpu")


def save_predictions(rows: Sequence[dict[str, Any]], path: str | Path) -> None:
    """Write per-instance predictions as CSV."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    fieldnames = list(rows[0])
    with open(path, "w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
